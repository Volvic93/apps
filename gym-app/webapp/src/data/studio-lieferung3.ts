function applyOwn(e: CatalogExercise): CatalogExercise {
  const o = OWN[e.id];
  if (!o) return e;
  const { primary, secondary, ...instr } = o;
  return {
    ...e,
    ...(primary ? { primaryMuscles: primary } : {}),
    ...(secondary ? { secondaryMuscles: secondary } : {}),
    instructions: { ...e.instructions, ...instr },
  };
}

export const LIEFERUNG3_UEBUNGEN: CatalogExercise[] = GENERIERT.map(applyOwn);
