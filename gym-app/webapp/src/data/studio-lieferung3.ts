/**
 * Dritte Fotolieferung (14.11.2026): weitere Geräte aus deinem Studio.
 * Die Übungen entstehen aus den allgemeinen Katalogübungen (Muskeln, Anleitung, Pausen werden übernommen,
 * die gerätespezifische Einstellung kommt davor) – so gibt es keine doppelten Texte.
 * Unsichere Zuordnungen tragen einen Hinweis „Bitte bestätigen“ und erscheinen in der App als „noch zu bestätigen“.
 */

function gen(
  id: string,
  name: string,
  equipmentId: string,
  genericId: string,
  o: { setup?: string; unilateral?: boolean; rest?: number; step?: number } = {},
): CatalogExercise {
  const base = KATALOG_UEBUNGEN.find((e) => e.id === `ex-${genericId}`);
  if (!base) throw new Error(`Allgemeine Übung fehlt: ${genericId}`);
  const { unilateral: _drop, ...rest } = base;
  void _drop;
  return {
    ...rest,
    id: `ex-${id}`,
    name,
    equipmentId,
    instructions: { ...base.instructions, setup: o.setup ? `${o.setup} ${base.instructions.setup}` : base.instructions.setup },
    defaultRestSec: o.rest ?? base.defaultRestSec,
    weightStep: o.step ?? base.weightStep,
    ...(o.unilateral ? { unilateral: true } : {}),
  };
}

